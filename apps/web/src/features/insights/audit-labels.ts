const automaticPrefixes = ['outbox.', 'configuration.', 'object_file.'];

/** Background bookkeeping by the system itself, hidden unless the user asks for it. */
export function isAutomaticAuditAction(action: string): boolean {
  return automaticPrefixes.some(prefix => action.startsWith(prefix));
}

export function auditActionLabel(action: string): string {
  return auditActionLabels[action] ?? (isAutomaticAuditAction(action) ? `Tarea automática (${action})` : `Otra acción (${action})`);
}
